-- WP13: balanced money ledger. PG-only; SQLite schema frozen.
-- Every journal balances debits = credits in its single currency (ILS).
-- Journals/entries are immutable; corrections are new reversal/adjustment
-- journals, never balance edits. Provider clearing here is the internal
-- cash-clearing account only: no bank/provider settlement is claimed (WP14).
CREATE TABLE ledger_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL CHECK(kind IN ('platform_revenue','driver_receivable','driver_payable','promo_expense','provider_clearing','customer_receivable','merchant_cod_payable')),
  owner_id BIGINT REFERENCES users(id),
  currency TEXT NOT NULL DEFAULT 'ILS' CHECK(currency = 'ILS'),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX ledger_accounts_owner ON ledger_accounts(owner_id, kind);

CREATE TABLE ledger_journals (
  id UUID PRIMARY KEY,
  business_ref TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL CHECK(kind IN ('commission_accrual','discount_funding','cash_collection','cash_remittance','cash_adjustment','refund','reversal','adjustment','opening_import')),
  currency TEXT NOT NULL DEFAULT 'ILS' CHECK(currency = 'ILS'),
  order_id BIGINT REFERENCES orders(id),
  cash_entry_id BIGINT,
  actor_id BIGINT REFERENCES users(id),
  reason TEXT,
  rate_bps BIGINT CHECK(rate_bps IS NULL OR rate_bps BETWEEN 0 AND 10000),
  reverses_journal_id UUID REFERENCES ledger_journals(id),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  CHECK(kind NOT IN ('reversal','adjustment') OR (reason IS NOT NULL AND length(reason) >= 5)),
  CHECK(kind <> 'reversal' OR reverses_journal_id IS NOT NULL)
);
CREATE INDEX ledger_journals_order ON ledger_journals(order_id, created_at);
CREATE INDEX ledger_journals_cash_entry ON ledger_journals(cash_entry_id) WHERE cash_entry_id IS NOT NULL;

CREATE TABLE ledger_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id UUID NOT NULL REFERENCES ledger_journals(id),
  account_id BIGINT NOT NULL REFERENCES ledger_accounts(id),
  debit_minor BIGINT NOT NULL DEFAULT 0 CHECK(debit_minor BETWEEN 0 AND 9007199254740991),
  credit_minor BIGINT NOT NULL DEFAULT 0 CHECK(credit_minor BETWEEN 0 AND 9007199254740991),
  CHECK((debit_minor > 0 AND credit_minor = 0) OR (credit_minor > 0 AND debit_minor = 0))
);
CREATE INDEX ledger_entries_journal ON ledger_entries(journal_id, id);
CREATE INDEX ledger_entries_account ON ledger_entries(account_id, id);

CREATE FUNCTION wp13_journal_balanced() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE jid uuid; debits numeric; credits numeric; lines bigint;
BEGIN
  IF TG_TABLE_NAME = 'ledger_journals' THEN
    jid := NEW.id;
  ELSE
    jid := NEW.journal_id;
  END IF;
  SELECT COALESCE(sum(debit_minor),0), COALESCE(sum(credit_minor),0), count(*) INTO debits, credits, lines FROM ledger_entries WHERE journal_id = jid;
  IF lines < 2 OR debits <> credits OR debits = 0 THEN
    RAISE EXCEPTION 'ledger journal must balance debits=credits with at least two entries' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ledger_entries_balanced AFTER INSERT ON ledger_entries
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION wp13_journal_balanced();
CREATE CONSTRAINT TRIGGER ledger_journals_balanced AFTER INSERT ON ledger_journals
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION wp13_journal_balanced();

CREATE TRIGGER ledger_accounts_immutable BEFORE UPDATE OR DELETE ON ledger_accounts FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE TRIGGER ledger_journals_immutable BEFORE UPDATE OR DELETE ON ledger_journals FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE TRIGGER ledger_entries_immutable BEFORE UPDATE OR DELETE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Cash facts: amount due, amount collected, who collected, and the receipt
-- reference are distinct columns; status moves are audited in events.
CREATE TABLE cash_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  driver_id BIGINT NOT NULL REFERENCES users(id),
  customer_id BIGINT NOT NULL REFERENCES users(id),
  due_minor BIGINT NOT NULL CHECK(due_minor BETWEEN 0 AND 9007199254740991),
  collected_minor BIGINT CHECK(collected_minor BETWEEN 0 AND 9007199254740991),
  collector_id BIGINT REFERENCES users(id),
  receipt_ref TEXT NOT NULL UNIQUE,
  currency TEXT NOT NULL DEFAULT 'ILS' CHECK(currency = 'ILS'),
  status TEXT NOT NULL CHECK(status IN ('due','collected','partial','returned','settled')),
  CHECK(status = 'due' OR collected_minor IS NOT NULL),
  CHECK(status <> 'collected' OR collected_minor = due_minor),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  collected_at BIGINT CHECK(collected_at BETWEEN 0 AND 9007199254740991),
  UNIQUE(order_id)
);
CREATE INDEX cash_receipts_driver ON cash_receipts(driver_id, id);
CREATE TABLE cash_receipt_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id BIGINT NOT NULL REFERENCES cash_receipts(id),
  action TEXT NOT NULL CHECK(action IN ('recorded','collected','partial','returned','settled','disputed','confirmed')),
  actor_id BIGINT NOT NULL REFERENCES users(id),
  amount_minor BIGINT CHECK(amount_minor BETWEEN 0 AND 9007199254740991),
  note TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX cash_receipt_events_receipt ON cash_receipt_events(receipt_id, id);
CREATE TRIGGER cash_receipt_events_append_only BEFORE UPDATE OR DELETE ON cash_receipt_events FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

