-- WP10: deterministic passenger dispatch. PG-only operational tables; no legacy
-- SQLite counterpart and no rows are seeded. Offers store only a nonce hash.
CREATE TABLE dispatch_rounds (
  id UUID PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  round_number BIGINT NOT NULL CHECK(round_number BETWEEN 1 AND 9007199254740991),
  state TEXT NOT NULL CHECK(state IN('open','matched','exhausted','cancelled')),
  close_reason TEXT CHECK(close_reason IN('matched','no_driver','deadline','cancelled')),
  started_at BIGINT NOT NULL CHECK(started_at BETWEEN 0 AND 9007199254740991),
  deadline_at BIGINT NOT NULL CHECK(deadline_at BETWEEN 0 AND 9007199254740991),
  offers_issued BIGINT NOT NULL DEFAULT 0 CHECK(offers_issued BETWEEN 0 AND 9007199254740991),
  closed_at BIGINT CHECK(closed_at BETWEEN 0 AND 9007199254740991),
  CHECK(deadline_at > started_at),
  CHECK((state='open' AND close_reason IS NULL AND closed_at IS NULL) OR (state<>'open' AND close_reason IS NOT NULL AND closed_at IS NOT NULL)),
  UNIQUE(order_id, round_number)
);
CREATE UNIQUE INDEX dispatch_rounds_one_open ON dispatch_rounds(order_id) WHERE state='open';
CREATE INDEX dispatch_rounds_order ON dispatch_rounds(order_id, round_number);
CREATE INDEX dispatch_rounds_open_deadline ON dispatch_rounds(deadline_at) WHERE state='open';

CREATE TABLE dispatch_offers (
  id UUID PRIMARY KEY,
  round_id UUID NOT NULL REFERENCES dispatch_rounds(id),
  order_id BIGINT NOT NULL REFERENCES orders(id),
  driver_id BIGINT NOT NULL REFERENCES users(id),
  state TEXT NOT NULL CHECK(state IN('open','accepted','declined','expired','revoked')),
  nonce_hash TEXT NOT NULL CHECK(nonce_hash ~ '^[a-f0-9]{64}$'),
  issued_at BIGINT NOT NULL CHECK(issued_at BETWEEN 0 AND 9007199254740991),
  expires_at BIGINT NOT NULL CHECK(expires_at BETWEEN 0 AND 9007199254740991),
  responded_at BIGINT CHECK(responded_at BETWEEN 0 AND 9007199254740991),
  order_revision BIGINT NOT NULL CHECK(order_revision BETWEEN 1 AND 9007199254740991),
  assignment_epoch BIGINT NOT NULL CHECK(assignment_epoch BETWEEN 0 AND 9007199254740991),
  presence_session_id UUID NOT NULL,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  driver_revision BIGINT NOT NULL,
  vehicle_revision BIGINT NOT NULL,
  policy_revision BIGINT NOT NULL,
  requirements_revision BIGINT NOT NULL,
  run_revision BIGINT NOT NULL,
  pickup_eta_seconds BIGINT NOT NULL CHECK(pickup_eta_seconds BETWEEN 0 AND 9007199254740991),
  idle_seconds BIGINT NOT NULL CHECK(idle_seconds BETWEEN 0 AND 9007199254740991),
  idle_credit_seconds BIGINT NOT NULL CHECK(idle_credit_seconds BETWEEN 0 AND 60),
  rank_score BIGINT NOT NULL,
  eta_estimated BIGINT NOT NULL CHECK(eta_estimated IN(0,1)),
  CHECK(expires_at > issued_at)
);
CREATE UNIQUE INDEX dispatch_offers_one_open_round ON dispatch_offers(round_id) WHERE state='open';
CREATE UNIQUE INDEX dispatch_offers_one_open_driver ON dispatch_offers(driver_id) WHERE state='open';
CREATE INDEX dispatch_offers_order ON dispatch_offers(order_id, issued_at);
CREATE INDEX dispatch_offers_open_expiry ON dispatch_offers(expires_at) WHERE state='open';

CREATE TABLE assignment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  driver_id BIGINT REFERENCES users(id),
  vehicle_id BIGINT REFERENCES vehicles(id),
  round_id UUID REFERENCES dispatch_rounds(id),
  offer_id UUID REFERENCES dispatch_offers(id),
  action TEXT NOT NULL CHECK(action IN('assigned','released','offer_accepted')),
  assignment_epoch BIGINT NOT NULL CHECK(assignment_epoch BETWEEN 0 AND 9007199254740991),
  actor_id BIGINT REFERENCES users(id),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX assignment_history_order ON assignment_history(order_id, id);

-- Every cancellation path (customer, partner, support, failed pickup) revokes
-- the open offer and closes its round in the cancelling transaction itself.
CREATE FUNCTION wp10_cancel_dispatch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  IF NEW.status='cancelled' AND OLD.status IS DISTINCT FROM 'cancelled' THEN
    UPDATE dispatch_offers SET state='revoked',responded_at=NEW.updated_at
      WHERE order_id=NEW.id AND state='open';
    UPDATE dispatch_rounds SET state='cancelled',close_reason='cancelled',closed_at=NEW.updated_at
      WHERE order_id=NEW.id AND state='open';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_wp10_cancel_dispatch AFTER UPDATE OF status ON orders FOR EACH ROW EXECUTE FUNCTION wp10_cancel_dispatch();
CREATE TRIGGER assignment_history_append_only BEFORE UPDATE OR DELETE ON assignment_history FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
