-- WP05 review repair, forward migration 7 after phone migration 6. Migration 5 is unchanged.
CREATE TABLE order_approaches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id), requirements_revision BIGINT NOT NULL CHECK(requirements_revision>0),
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id), vehicle_revision BIGINT NOT NULL CHECK(vehicle_revision>0),
  run_revision BIGINT NOT NULL CHECK(run_revision>=0),
  from_lng DOUBLE PRECISION NOT NULL CHECK(from_lng BETWEEN -180 AND 180), from_lat DOUBLE PRECISION NOT NULL CHECK(from_lat BETWEEN -90 AND 90),
  to_lng DOUBLE PRECISION NOT NULL CHECK(to_lng BETWEEN -180 AND 180), to_lat DOUBLE PRECISION NOT NULL CHECK(to_lat BETWEEN -90 AND 90),
  seconds BIGINT NOT NULL CHECK(seconds BETWEEN 1 AND 86400), observed_at BIGINT NOT NULL,
  valid_until BIGINT NOT NULL CHECK(valid_until>observed_at AND valid_until<=observed_at+86400000),
  method TEXT NOT NULL CHECK(method='operator_attested'), reviewer_id BIGINT NOT NULL REFERENCES users(id),
  evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  CHECK(observed_at<=created_at AND observed_at>=created_at-300000)
);
CREATE INDEX order_approaches_candidate ON order_approaches(order_id,vehicle_id,id DESC);
CREATE TRIGGER order_approaches_immutable BEFORE UPDATE OR DELETE ON order_approaches FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Validate canonical integer physical resources using NUMERIC arithmetic before comparing sums.
-- JSON values are bounded before arithmetic; adversarial products cannot overflow BIGINT.
CREATE FUNCTION wp05_resources_valid(q order_requirements) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE item jsonb; k text; n numeric; grams numeric:=0; volume numeric:=0; pieces numeric:=0;
BEGIN
  IF jsonb_typeof(q.items)<>'array' OR jsonb_array_length(q.items)>200 OR jsonb_typeof(q.equipment)<>'array'
    OR q.rotation_policy<>'fixed_axes_no_stacking' THEN RETURN false; END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(q.items) LOOP
    IF jsonb_typeof(item)<>'object' THEN RETURN false; END IF;
    FOREACH k IN ARRAY ARRAY['count','gramsEach','lengthMm','widthMm','heightMm'] LOOP
      IF jsonb_typeof(item->k) IS DISTINCT FROM 'number' OR (item->>k)!~'^[0-9]{1,10}$' THEN RETURN false; END IF;
      n:=(item->>k)::numeric;
      IF n<1 OR n>(CASE WHEN k='count' THEN 200 WHEN k='gramsEach' THEN 1000000000 ELSE 100000 END) THEN RETURN false; END IF;
    END LOOP;
    pieces:=pieces+(item->>'count')::numeric;
    grams:=grams+(item->>'count')::numeric*(item->>'gramsEach')::numeric;
    volume:=volume+(item->>'count')::numeric*ceil((item->>'lengthMm')::numeric*(item->>'widthMm')::numeric*(item->>'heightMm')::numeric/1000);
  END LOOP;
  RETURN pieces=q.pieces AND grams=q.grams AND volume=q.cm3;
END $$;

-- Keep policy evaluation in the domain. This guard enforces the physical certificate, shared
-- resources and canonical scope under vehicle/run locks even when a writer skips the API.
CREATE OR REPLACE FUNCTION wp05_assignment_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d driver_eligibility%ROWTYPE; r capacity_reservations%ROWTYPE; v vehicles%ROWTYPE;
  q order_requirements%ROWTYPE; prior record; item jsonb; run_revision bigint; policy_revision bigint;
  total_grams numeric:=0; total_volume numeric:=0; total_pieces numeric:=0; total_seats numeric:=0; total_length numeric:=0;
  now_ms bigint:=floor(extract(epoch FROM clock_timestamp())*1000);
BEGIN
  IF NEW.driver_id IS NULL OR NEW.status NOT IN('assigned','at_pickup','in_transit','on_hold','returning') THEN RETURN NEW; END IF;
  IF TG_OP='UPDATE' AND OLD.driver_id IS NOT DISTINCT FROM NEW.driver_id AND OLD.status IN('assigned','at_pickup','in_transit','on_hold','returning') THEN RETURN NEW; END IF;
  SELECT * INTO d FROM driver_eligibility WHERE driver_id=NEW.driver_id FOR UPDATE;
  IF NOT FOUND THEN
    IF EXISTS(SELECT 1 FROM order_requirements WHERE order_id=NEW.id) THEN RAISE EXCEPTION 'measured enrollment required' USING ERRCODE='23514'; END IF;
    RETURN NEW;
  END IF;
  SELECT * INTO v FROM vehicles WHERE id=d.vehicle_id FOR UPDATE;
  SELECT revision INTO run_revision FROM vehicle_runs WHERE vehicle_id=v.id FOR UPDATE;
  IF EXISTS(SELECT 1 FROM orders o JOIN driver_eligibility selected ON selected.driver_id=o.driver_id
    WHERE selected.vehicle_id=v.id AND o.id<>NEW.id AND o.status IN('assigned','at_pickup','in_transit','on_hold','returning')
    AND (NEW.service<>'parcel' OR o.service<>'parcel')) THEN
    RAISE EXCEPTION 'shared vehicle incompatible commitment' USING ERRCODE='23514'; END IF;
  IF d.enrolled<>1 THEN
    IF EXISTS(SELECT 1 FROM order_requirements WHERE order_id=NEW.id) OR EXISTS(SELECT 1 FROM capacity_reservations c JOIN orders o ON o.id=c.order_id WHERE c.vehicle_id=v.id
      AND o.status IN('assigned','at_pickup','in_transit','on_hold','returning')) THEN
      RAISE EXCEPTION 'unknown load cannot join measured vehicle' USING ERRCODE='23514'; END IF;
    RETURN NEW;
  END IF;
  SELECT revision INTO policy_revision FROM eligibility_policy WHERE id=1;
  SELECT * INTO q FROM order_requirements WHERE order_id=NEW.id FOR SHARE;
  SELECT * INTO r FROM capacity_reservations WHERE order_id=NEW.id FOR UPDATE;
  IF q.order_id IS NULL OR r.order_id IS NULL OR r.driver_id<>NEW.driver_id OR r.vehicle_id<>v.id OR r.vehicle_revision<>v.revision
    OR r.driver_revision<>d.revision OR r.policy_revision<>policy_revision OR r.requirements_revision<>q.revision OR r.run_revision IS DISTINCT FROM run_revision
    OR (r.grams,r.cm3,r.pieces,r.seats,r.service) IS DISTINCT FROM (q.grams,q.cm3,q.pieces,q.seats,NEW.service)
    OR r.evidence_kind<>'new_acceptance' OR d.state<>'approved' OR v.state<>'approved' OR v.inspection_required<>0
    OR d.valid_until<=r.planned_end OR v.valid_until<=r.planned_end OR r.planned_end<=now_ms
    OR NOT EXISTS(SELECT 1 FROM users u WHERE u.id=NEW.driver_id AND u.role='driver' AND u.status='active' AND u.vehicle=v.class) THEN
    RAISE EXCEPTION 'canonical measured reservation required' USING ERRCODE='23514'; END IF;
  FOR prior IN
    SELECT NEW.id order_id,NEW.service service,NEW.driver_id driver_id,NEW.option booked_option
    UNION ALL SELECT o.id,o.service,o.driver_id,o.option FROM orders o JOIN driver_eligibility selected ON selected.driver_id=o.driver_id
      WHERE selected.vehicle_id=v.id AND o.id<>NEW.id AND o.status IN('assigned','at_pickup','in_transit','on_hold','returning')
  LOOP
    SELECT * INTO q FROM order_requirements WHERE order_id=prior.order_id FOR SHARE;
    SELECT * INTO r FROM capacity_reservations WHERE order_id=prior.order_id FOR UPDATE;
    IF q.order_id IS NULL OR r.order_id IS NULL OR r.vehicle_id<>v.id OR r.driver_id<>prior.driver_id
      OR r.requirements_revision<>q.revision OR (r.grams,r.cm3,r.pieces,r.seats,r.service) IS DISTINCT FROM (q.grams,q.cm3,q.pieces,q.seats,prior.service)
      OR NOT wp05_resources_valid(q) OR NOT q.equipment <@ v.equipment
      OR (prior.service='ride' AND (q.seats<1 OR q.pieces<>0)) OR (prior.service<>'ride' AND (q.seats<>0 OR q.pieces<1)) THEN
      RAISE EXCEPTION 'invalid physical scope or unknown prior load' USING ERRCODE='23514'; END IF;
    IF prior.service='ride' THEN
      IF prior.booked_option!~'^[0-9]{1,3}$' THEN RAISE EXCEPTION 'invalid booked seats' USING ERRCODE='23514'; END IF;
      IF q.seats<prior.booked_option::numeric THEN RAISE EXCEPTION 'booked seats understated' USING ERRCODE='23514'; END IF;
    END IF;
    total_grams:=total_grams+q.grams; total_volume:=total_volume+q.cm3; total_pieces:=total_pieces+q.pieces; total_seats:=total_seats+q.seats;
    FOR item IN SELECT value FROM jsonb_array_elements(q.items) LOOP
      IF (item->>'lengthMm')::numeric>v.length_mm OR (item->>'widthMm')::numeric>v.width_mm OR (item->>'heightMm')::numeric>v.height_mm THEN
        RAISE EXCEPTION 'fixed axis dimensions exceeded' USING ERRCODE='23514'; END IF;
      total_length:=total_length+(item->>'count')::numeric*(item->>'lengthMm')::numeric;
    END LOOP;
  END LOOP;
  IF total_grams>v.usable_grams OR total_volume>v.usable_cm3 OR total_pieces>least(200,v.max_pieces) OR total_seats>v.seats OR total_length>v.length_mm THEN
    RAISE EXCEPTION 'shared physical capacity exceeded' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $$;

