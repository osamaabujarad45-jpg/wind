-- WP07: opt-in latest-fix presence. No raw movement history or online drivers are seeded.
CREATE UNIQUE INDEX sessions_presence_owner ON sessions(token_hash, user_id);
CREATE TABLE driver_presence_sessions (
  id UUID PRIMARY KEY,
  driver_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  auth_session_hash TEXT NOT NULL,
  device_hash TEXT NOT NULL,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  driver_revision BIGINT NOT NULL,
  vehicle_revision BIGINT NOT NULL,
  policy_revision BIGINT NOT NULL,
  consent_version BIGINT NOT NULL CHECK(consent_version=1),
  consented_at BIGINT NOT NULL,
  started_at BIGINT NOT NULL,
  heartbeat_at BIGINT NOT NULL,
  lease_until BIGINT NOT NULL,
  heartbeat_seq BIGINT NOT NULL DEFAULT 0 CHECK(heartbeat_seq BETWEEN 0 AND 9007199254740991),
  location_seq BIGINT NOT NULL DEFAULT 0 CHECK(location_seq BETWEEN 0 AND 9007199254740991),
  state TEXT NOT NULL CHECK(state IN('online','offline')),
  UNIQUE(id, driver_id),
  FOREIGN KEY(auth_session_hash, driver_id) REFERENCES sessions(token_hash, user_id) ON DELETE CASCADE
);
CREATE INDEX driver_presence_lease ON driver_presence_sessions(lease_until) WHERE state='online';

CREATE TABLE driver_latest_locations (
  driver_id BIGINT PRIMARY KEY REFERENCES users(id),
  session_id UUID NOT NULL,
  lat DOUBLE PRECISION NOT NULL CHECK(lat BETWEEN -90 AND 90),
  lng DOUBLE PRECISION NOT NULL CHECK(lng BETWEEN -180 AND 180),
  accuracy DOUBLE PRECISION CHECK(accuracy BETWEEN 0 AND 5000),
  heading DOUBLE PRECISION CHECK(heading BETWEEN 0 AND 360),
  effective_at BIGINT NOT NULL,
  received_at BIGINT NOT NULL,
  seq BIGINT NOT NULL CHECK(seq BETWEEN 1 AND 9007199254740991),
  good_lat DOUBLE PRECISION NOT NULL CHECK(good_lat BETWEEN -90 AND 90),
  good_lng DOUBLE PRECISION NOT NULL CHECK(good_lng BETWEEN -180 AND 180),
  good_at BIGINT NOT NULL,
  good_accuracy DOUBLE PRECISION NOT NULL CHECK(good_accuracy BETWEEN 0 AND 5000),
  FOREIGN KEY(session_id, driver_id) REFERENCES driver_presence_sessions(id, driver_id) ON DELETE CASCADE,
  position geometry(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lng,lat),4326)) STORED
);
CREATE INDEX driver_latest_positions ON driver_latest_locations USING GIST(position);

-- Consent/availability audit carries no coordinates, device IDs, bearer token or phone.
CREATE TABLE driver_presence_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id BIGINT NOT NULL REFERENCES users(id),
  session_id UUID NOT NULL,
  action TEXT NOT NULL CHECK(action IN('online','offline')),
  consent_version BIGINT NOT NULL CHECK(consent_version=1),
  occurred_at BIGINT NOT NULL
);
CREATE TRIGGER driver_presence_audit_immutable BEFORE UPDATE OR DELETE ON driver_presence_audit FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Account suspension or a role change ends pre-assignment collection immediately.
-- Deleting an authentication session also cascades to its presence and latest fix.
CREATE FUNCTION wp07_end_ineligible_presence() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  IF NEW.role<>'driver' OR NEW.status<>'active' THEN
    DELETE FROM driver_presence_sessions WHERE driver_id=NEW.id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER users_wp07_end_presence AFTER UPDATE OF role,status ON users FOR EACH ROW EXECUTE FUNCTION wp07_end_ineligible_presence();
