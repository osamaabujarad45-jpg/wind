-- WP08: versioned road_restrictions and immutable quotes
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE TABLE road_restriction_policy (
  id BIGINT PRIMARY KEY CHECK(id=1),
  revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
  activated BIGINT NOT NULL DEFAULT 0 CHECK(activated IN (0,1)),
  evidence_ref TEXT,
  reviewer_id BIGINT REFERENCES users(id),
  reason TEXT,
  reviewed_at BIGINT CHECK(reviewed_at BETWEEN 0 AND 9007199254740991)
);
INSERT INTO road_restriction_policy(id) VALUES(1);

CREATE TABLE road_restrictions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
  restriction_key TEXT NOT NULL,
  version BIGINT NOT NULL CHECK(version BETWEEN 1 AND 9007199254740991),
  state TEXT NOT NULL CHECK(state IN ('open','closed','restricted','unknown','suspended')),
  services JSONB NOT NULL,
  vehicle_classes JSONB NOT NULL,
  geometry geometry(LineString,4326) NOT NULL CHECK(ST_IsValid(geometry) AND NOT ST_IsEmpty(geometry)),
  direction TEXT NOT NULL CHECK(direction IN ('bidirectional','forward','backward')),
  source TEXT NOT NULL,
  valid_from BIGINT NOT NULL CHECK(valid_from BETWEEN 0 AND 9007199254740991),
  valid_until BIGINT NOT NULL CHECK(valid_until BETWEEN 0 AND 9007199254740991),
  last_confirmed_at BIGINT NOT NULL CHECK(last_confirmed_at BETWEEN 0 AND 9007199254740991),
  confidence TEXT NOT NULL CHECK(confidence IN ('high','medium','low','unknown')),
  confirmed_prohibition BOOLEAN NOT NULL,
  reviewer_id BIGINT NOT NULL REFERENCES users(id),
  evidence_ref TEXT NOT NULL,
  reason TEXT NOT NULL,
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  UNIQUE(restriction_key, version),
  CHECK(valid_until > valid_from)
);
CREATE INDEX road_restrictions_geometry_gist ON road_restrictions USING GIST(geometry);
CREATE INDEX road_restrictions_key ON road_restrictions(restriction_key);
CREATE TRIGGER road_restrictions_immutable BEFORE UPDATE OR DELETE ON road_restrictions FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

CREATE TABLE quotes (
  id UUID PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  service TEXT NOT NULL CHECK(service IN ('ride','parcel','freight')),
  pickup_city TEXT NOT NULL,
  dropoff_city TEXT NOT NULL,
  pickup_lat DOUBLE PRECISION CHECK(pickup_lat BETWEEN -90 AND 90),
  pickup_lng DOUBLE PRECISION CHECK(pickup_lng BETWEEN -180 AND 180),
  dropoff_lat DOUBLE PRECISION CHECK(dropoff_lat BETWEEN -90 AND 90),
  dropoff_lng DOUBLE PRECISION CHECK(dropoff_lng BETWEEN -180 AND 180),
  pickup_note TEXT NOT NULL,
  dropoff_note TEXT NOT NULL,
  contact TEXT NOT NULL,
  pickup_contact TEXT,
  recipient_name TEXT,
  recipient_phone TEXT,
  detail TEXT NOT NULL,
  option TEXT NOT NULL,
  loading_help BIGINT NOT NULL CHECK(loading_help IN (0,1)),
  shared BIGINT NOT NULL CHECK(shared IN (0,1)),
  scheduled_for BIGINT CHECK(scheduled_for BETWEEN 0 AND 9007199254740991),
  currency TEXT NOT NULL DEFAULT 'ILS' CHECK(currency='ILS'),
  price_minor BIGINT NOT NULL CHECK(price_minor BETWEEN 1 AND 9007199254740991),
  discount_minor BIGINT CHECK(discount_minor BETWEEN 0 AND 9007199254740991),
  commission_minor BIGINT CHECK(commission_minor BETWEEN 0 AND 9007199254740991),
  tariff_snapshot JSONB NOT NULL,
  tariff_basis_points JSONB NOT NULL,
  tariff_version TEXT NOT NULL,
  graph_version TEXT,
  profile_version TEXT,
  restriction_version TEXT,
  provider_version TEXT,
  eta_min_seconds BIGINT NOT NULL CHECK(eta_min_seconds BETWEEN 0 AND 9007199254740991),
  eta_max_seconds BIGINT NOT NULL CHECK(eta_max_seconds BETWEEN 0 AND 9007199254740991),
  feasibility TEXT NOT NULL CHECK(feasibility IN ('feasible','infeasible','uncertain')),
  reasons JSONB NOT NULL,
  disclosures JSONB NOT NULL,
  lines JSONB NOT NULL,
  itinerary_hash TEXT NOT NULL,
  expires_at BIGINT NOT NULL CHECK(expires_at BETWEEN 0 AND 9007199254740991),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  consumed_at BIGINT CHECK(consumed_at BETWEEN 0 AND 9007199254740991),
  consumed_order_id BIGINT REFERENCES orders(id),
  CHECK(eta_max_seconds >= eta_min_seconds),
  CHECK(expires_at > created_at)
);
CREATE INDEX quotes_customer_created ON quotes(customer_id, created_at);
CREATE INDEX quotes_expires ON quotes(expires_at);
CREATE INDEX quotes_consumed_order ON quotes(consumed_order_id) WHERE consumed_order_id IS NOT NULL;

ALTER TABLE orders ADD COLUMN quote_id UUID REFERENCES quotes(id);
CREATE INDEX orders_quote ON orders(quote_id) WHERE quote_id IS NOT NULL;

CREATE FUNCTION quotes_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'quotes are immutable' USING ERRCODE='23514'; END IF;
  IF OLD.id IS DISTINCT FROM NEW.id OR OLD.customer_id IS DISTINCT FROM NEW.customer_id OR OLD.service IS DISTINCT FROM NEW.service
    OR OLD.pickup_city IS DISTINCT FROM NEW.pickup_city OR OLD.dropoff_city IS DISTINCT FROM NEW.dropoff_city
    OR OLD.pickup_lat IS DISTINCT FROM NEW.pickup_lat OR OLD.pickup_lng IS DISTINCT FROM NEW.pickup_lng
    OR OLD.dropoff_lat IS DISTINCT FROM NEW.dropoff_lat OR OLD.dropoff_lng IS DISTINCT FROM NEW.dropoff_lng
    OR OLD.pickup_note IS DISTINCT FROM NEW.pickup_note OR OLD.dropoff_note IS DISTINCT FROM NEW.dropoff_note
    OR OLD.contact IS DISTINCT FROM NEW.contact OR OLD.pickup_contact IS DISTINCT FROM NEW.pickup_contact
    OR OLD.recipient_name IS DISTINCT FROM NEW.recipient_name OR OLD.recipient_phone IS DISTINCT FROM NEW.recipient_phone
    OR OLD.detail IS DISTINCT FROM NEW.detail OR OLD.option IS DISTINCT FROM NEW.option
    OR OLD.loading_help IS DISTINCT FROM NEW.loading_help OR OLD.shared IS DISTINCT FROM NEW.shared
    OR OLD.scheduled_for IS DISTINCT FROM NEW.scheduled_for OR OLD.currency IS DISTINCT FROM NEW.currency
    OR OLD.price_minor IS DISTINCT FROM NEW.price_minor OR OLD.discount_minor IS DISTINCT FROM NEW.discount_minor
    OR OLD.commission_minor IS DISTINCT FROM NEW.commission_minor OR OLD.tariff_snapshot IS DISTINCT FROM NEW.tariff_snapshot
    OR OLD.tariff_basis_points IS DISTINCT FROM NEW.tariff_basis_points OR OLD.tariff_version IS DISTINCT FROM NEW.tariff_version
    OR OLD.graph_version IS DISTINCT FROM NEW.graph_version OR OLD.profile_version IS DISTINCT FROM NEW.profile_version
    OR OLD.restriction_version IS DISTINCT FROM NEW.restriction_version OR OLD.provider_version IS DISTINCT FROM NEW.provider_version
    OR OLD.eta_min_seconds IS DISTINCT FROM NEW.eta_min_seconds OR OLD.eta_max_seconds IS DISTINCT FROM NEW.eta_max_seconds
    OR OLD.feasibility IS DISTINCT FROM NEW.feasibility OR OLD.reasons IS DISTINCT FROM NEW.reasons
    OR OLD.disclosures IS DISTINCT FROM NEW.disclosures OR OLD.lines IS DISTINCT FROM NEW.lines
    OR OLD.itinerary_hash IS DISTINCT FROM NEW.itinerary_hash OR OLD.expires_at IS DISTINCT FROM NEW.expires_at
    OR OLD.created_at IS DISTINCT FROM NEW.created_at
  THEN RAISE EXCEPTION 'quotes are immutable' USING ERRCODE='23514'; END IF;
  IF OLD.consumed_at IS NOT NULL AND (NEW.consumed_at IS DISTINCT FROM OLD.consumed_at OR NEW.consumed_order_id IS DISTINCT FROM OLD.consumed_order_id)
  THEN RAISE EXCEPTION 'quote already consumed' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER quotes_immutable_trigger BEFORE UPDATE ON quotes FOR EACH ROW EXECUTE FUNCTION quotes_immutable();
