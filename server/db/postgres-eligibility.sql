-- WP05: additive, unactivated evidence. No jurisdiction/permit/vehicle data is seeded.
CREATE TABLE eligibility_policy (
  id BIGINT PRIMARY KEY CHECK(id=1), revision BIGINT NOT NULL DEFAULT 1,
  activated BIGINT NOT NULL DEFAULT 0 CHECK(activated IN(0,1)),
  evidence_ref TEXT, reviewer_id BIGINT REFERENCES users(id), reason TEXT, reviewed_at BIGINT
);
INSERT INTO eligibility_policy(id) VALUES(1);
CREATE TABLE service_areas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_key TEXT NOT NULL, version BIGINT NOT NULL, state TEXT NOT NULL CHECK(state IN('approved','suspended')),
  services JSONB NOT NULL, vehicle_classes JSONB NOT NULL, required_permits JSONB NOT NULL,
  valid_from BIGINT NOT NULL, valid_until BIGINT NOT NULL CHECK(valid_until>valid_from),
  geometry geometry(MultiPolygon,4326) NOT NULL CHECK(ST_IsValid(geometry) AND NOT ST_IsEmpty(geometry)),
  reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE(area_key,version)
);
CREATE INDEX service_areas_geometry_gist ON service_areas USING GIST(geometry);
CREATE TABLE route_permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_key TEXT NOT NULL, version BIGINT NOT NULL, from_area_id BIGINT NOT NULL REFERENCES service_areas(id),
  to_area_id BIGINT NOT NULL REFERENCES service_areas(id), state TEXT NOT NULL CHECK(state IN('approved','suspended')),
  services JSONB NOT NULL, vehicle_classes JSONB NOT NULL, required_permits JSONB NOT NULL,
  valid_from BIGINT NOT NULL, valid_until BIGINT NOT NULL CHECK(valid_until>valid_from),
  corridor geometry(MultiPolygon,4326) NOT NULL CHECK(ST_IsValid(corridor) AND NOT ST_IsEmpty(corridor)),
  reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE(route_key,version)
);
CREATE INDEX route_permissions_corridor_gist ON route_permissions USING GIST(corridor);
CREATE TABLE vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plate TEXT NOT NULL UNIQUE, class TEXT NOT NULL,
  revision BIGINT NOT NULL DEFAULT 1, state TEXT NOT NULL CHECK(state IN('draft','submitted','under_review','approved','changes_required','rejected','suspended','expired')),
  seats BIGINT NOT NULL CHECK(seats BETWEEN 0 AND 100), usable_grams BIGINT NOT NULL CHECK(usable_grams BETWEEN 0 AND 1000000000),
  usable_cm3 BIGINT NOT NULL CHECK(usable_cm3 BETWEEN 0 AND 1000000000),
  length_mm BIGINT NOT NULL CHECK(length_mm BETWEEN 0 AND 100000), width_mm BIGINT NOT NULL CHECK(width_mm BETWEEN 0 AND 100000),
  height_mm BIGINT NOT NULL CHECK(height_mm BETWEEN 0 AND 100000), max_pieces BIGINT NOT NULL CHECK(max_pieces BETWEEN 1 AND 200),
  equipment JSONB NOT NULL, inspection_required BIGINT NOT NULL DEFAULT 0 CHECK(inspection_required IN(0,1)),
  valid_until BIGINT NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE driver_eligibility (
  driver_id BIGINT PRIMARY KEY REFERENCES users(id), vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  revision BIGINT NOT NULL DEFAULT 1, enrolled BIGINT NOT NULL DEFAULT 0 CHECK(enrolled IN(0,1)),
  state TEXT NOT NULL CHECK(state IN('draft','submitted','under_review','approved','changes_required','rejected','suspended','expired')),
  valid_until BIGINT NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE driver_vehicles (
  driver_id BIGINT NOT NULL REFERENCES users(id), vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  reviewer_id BIGINT NOT NULL REFERENCES users(id), reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  PRIMARY KEY(driver_id,vehicle_id)
);
CREATE TABLE verification_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id BIGINT REFERENCES users(id), vehicle_id BIGINT REFERENCES vehicles(id),
  vehicle_revision BIGINT, kind TEXT NOT NULL CHECK(kind IN('driver_license','vehicle_registration','vehicle_inspection','permit')),
  permit_key TEXT NOT NULL DEFAULT '', outcome TEXT NOT NULL CHECK(outcome IN('approved','rejected','invalid','suspended')),
  valid_from BIGINT NOT NULL, expires_at BIGINT NOT NULL CHECK(expires_at>valid_from),
  method TEXT NOT NULL CHECK(method IN('manual_in_person','operator_registry')),
  issuer TEXT NOT NULL, evidence_ref TEXT NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES users(id), reason TEXT NOT NULL, created_at BIGINT NOT NULL,
  CHECK((driver_id IS NULL) <> (vehicle_id IS NULL)), CHECK((kind='permit') = (permit_key<>'')),
  CHECK((kind='driver_license' AND driver_id IS NOT NULL) OR kind='permit' OR (kind IN('vehicle_registration','vehicle_inspection') AND vehicle_id IS NOT NULL))
);
CREATE TABLE order_requirements (
  order_id BIGINT PRIMARY KEY REFERENCES orders(id), revision BIGINT NOT NULL DEFAULT 1,
  grams BIGINT NOT NULL CHECK(grams BETWEEN 0 AND 1000000000), cm3 BIGINT NOT NULL CHECK(cm3 BETWEEN 0 AND 1000000000),
  pieces BIGINT NOT NULL CHECK(pieces BETWEEN 0 AND 200), seats BIGINT NOT NULL CHECK(seats BETWEEN 0 AND 100),
  items JSONB NOT NULL, equipment JSONB NOT NULL,
  rotation_policy TEXT NOT NULL CHECK(rotation_policy='fixed_axes_no_stacking'),
  route geometry(LineString,4326) NOT NULL CHECK(ST_IsValid(route) AND NOT ST_IsEmpty(route)),
  route_seconds BIGINT NOT NULL CHECK(route_seconds BETWEEN 1 AND 86400), service_seconds BIGINT NOT NULL CHECK(service_seconds BETWEEN 0 AND 86400),
  pickup_after BIGINT NOT NULL, pickup_before BIGINT NOT NULL, dropoff_before BIGINT NOT NULL CHECK(dropoff_before>=pickup_before AND pickup_before>=pickup_after),
  reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE vehicle_runs (
  vehicle_id BIGINT PRIMARY KEY REFERENCES vehicles(id), revision BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE capacity_reservations (
  order_id BIGINT PRIMARY KEY REFERENCES orders(id), vehicle_id BIGINT NOT NULL REFERENCES vehicles(id), driver_id BIGINT NOT NULL REFERENCES users(id),
  vehicle_revision BIGINT NOT NULL, driver_revision BIGINT NOT NULL, policy_revision BIGINT NOT NULL, requirements_revision BIGINT NOT NULL,
  run_revision BIGINT NOT NULL, grams BIGINT NOT NULL, cm3 BIGINT NOT NULL, pieces BIGINT NOT NULL, seats BIGINT NOT NULL,
  service TEXT NOT NULL, planned_end BIGINT NOT NULL, created_at BIGINT NOT NULL,
  evidence_kind TEXT NOT NULL DEFAULT 'new_acceptance' CHECK(evidence_kind IN('new_acceptance','legacy_inspection'))
);
CREATE INDEX capacity_reservations_vehicle ON capacity_reservations(vehicle_id);
CREATE TABLE capacity_stops (
  order_id BIGINT NOT NULL REFERENCES orders(id), position BIGINT NOT NULL CHECK(position IN(0,1)),
  kind TEXT NOT NULL CHECK(kind IN('pickup','dropoff')), not_before BIGINT NOT NULL, not_after BIGINT NOT NULL,
  service_seconds BIGINT NOT NULL, grams_delta BIGINT NOT NULL, cm3_delta BIGINT NOT NULL, pieces_delta BIGINT NOT NULL,
  PRIMARY KEY(order_id,position), CHECK((position=0 AND kind='pickup') OR (position=1 AND kind='dropoff'))
);
CREATE TABLE eligibility_offers (
  order_id BIGINT NOT NULL REFERENCES orders(id), driver_id BIGINT NOT NULL REFERENCES users(id),
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id), vehicle_revision BIGINT NOT NULL, driver_revision BIGINT NOT NULL,
  policy_revision BIGINT NOT NULL, requirements_revision BIGINT NOT NULL, run_revision BIGINT NOT NULL, created_at BIGINT NOT NULL,
  PRIMARY KEY(order_id,driver_id)
);
CREATE TABLE eligibility_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL REFERENCES users(id),
  action TEXT NOT NULL, subject_id BIGINT NOT NULL, reason TEXT NOT NULL, evidence_ref TEXT, created_at BIGINT NOT NULL
);
CREATE FUNCTION wp05_append_only() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  RAISE EXCEPTION 'record is append-only' USING ERRCODE='23514'; END $$;
CREATE TRIGGER eligibility_audit_immutable BEFORE UPDATE OR DELETE ON eligibility_audit FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE TRIGGER verification_checks_immutable BEFORE UPDATE OR DELETE ON verification_checks FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE TRIGGER service_areas_immutable BEFORE UPDATE OR DELETE ON service_areas FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE TRIGGER route_permissions_immutable BEFORE UPDATE OR DELETE ON route_permissions FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Direct writers cannot bypass enrollment or the shared physical vehicle. Transitions of existing
-- custody are deliberately exempt; expiry/suspension must never erase or strand a retained load.
CREATE FUNCTION wp05_assignment_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d driver_eligibility%ROWTYPE; r capacity_reservations%ROWTYPE; v vehicles%ROWTYPE;
BEGIN
  IF NEW.driver_id IS NULL OR NEW.status NOT IN('assigned','at_pickup','in_transit','on_hold','returning') THEN RETURN NEW; END IF;
  IF TG_OP='UPDATE' AND OLD.driver_id IS NOT DISTINCT FROM NEW.driver_id AND OLD.status IN('assigned','at_pickup','in_transit','on_hold','returning') THEN RETURN NEW; END IF;
  SELECT * INTO d FROM driver_eligibility WHERE driver_id=NEW.driver_id FOR UPDATE;
  IF NOT FOUND THEN RETURN NEW; END IF;
  SELECT * INTO v FROM vehicles WHERE id=d.vehicle_id FOR UPDATE;
  PERFORM vehicle_id FROM vehicle_runs WHERE vehicle_id=v.id FOR UPDATE;
  IF EXISTS(SELECT 1 FROM orders o JOIN driver_vehicles dv ON dv.driver_id=o.driver_id
    JOIN driver_eligibility selected ON selected.driver_id=dv.driver_id AND selected.vehicle_id=dv.vehicle_id
    WHERE dv.vehicle_id=v.id AND o.id<>NEW.id AND o.status IN('assigned','at_pickup','in_transit','on_hold','returning')
    AND (NEW.service<>'parcel' OR o.service<>'parcel')) THEN
    RAISE EXCEPTION 'shared vehicle incompatible commitment' USING ERRCODE='23514'; END IF;
  IF d.enrolled=1 THEN
    SELECT * INTO r FROM capacity_reservations WHERE order_id=NEW.id;
    IF NOT FOUND OR r.driver_id<>NEW.driver_id OR r.vehicle_id<>v.id OR r.vehicle_revision<>v.revision OR r.driver_revision<>d.revision
      OR r.policy_revision<>(SELECT revision FROM eligibility_policy WHERE id=1) OR d.state<>'approved' OR v.state<>'approved'
      OR d.valid_until <= floor(extract(epoch FROM clock_timestamp())*1000) OR v.valid_until <= floor(extract(epoch FROM clock_timestamp())*1000) THEN
      RAISE EXCEPTION 'measured eligibility reservation required' USING ERRCODE='23514'; END IF;
  ELSIF EXISTS(SELECT 1 FROM capacity_reservations c JOIN orders o ON o.id=c.order_id WHERE c.vehicle_id=v.id
    AND o.status IN('assigned','at_pickup','in_transit','on_hold','returning')) THEN
    RAISE EXCEPTION 'unknown load cannot join measured vehicle' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_wp05_assignment_guard BEFORE INSERT OR UPDATE OF driver_id,status,service ON orders FOR EACH ROW EXECUTE FUNCTION wp05_assignment_guard();

-- Installed admin/profile writers also fence measured evidence; reactivating a legacy user
-- is not a new measured approval. Existing custody stays in the same public lifecycle.
CREATE FUNCTION wp05_identity_revision() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  IF (NEW.phone,NEW.email,NEW.role,NEW.vehicle,NEW.status) IS DISTINCT FROM (OLD.phone,OLD.email,OLD.role,OLD.vehicle,OLD.status) THEN
    UPDATE driver_eligibility SET revision=revision+1,
      state=CASE WHEN NEW.status='blocked' THEN 'suspended'
        WHEN (NEW.phone,NEW.email,NEW.role,NEW.vehicle) IS DISTINCT FROM (OLD.phone,OLD.email,OLD.role,OLD.vehicle) OR NEW.status='pending' THEN 'under_review'
        ELSE state END WHERE driver_id=NEW.id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER users_wp05_revision AFTER UPDATE ON users FOR EACH ROW EXECUTE FUNCTION wp05_identity_revision();
CREATE FUNCTION wp05_run_revision() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
  IF (NEW.driver_id,NEW.status) IS DISTINCT FROM (OLD.driver_id,OLD.status) THEN
    UPDATE vehicle_runs SET revision=revision+1 WHERE vehicle_id IN(SELECT vehicle_id FROM capacity_reservations WHERE order_id=NEW.id);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_wp05_run_revision AFTER UPDATE OF driver_id,status ON orders FOR EACH ROW EXECUTE FUNCTION wp05_run_revision();
