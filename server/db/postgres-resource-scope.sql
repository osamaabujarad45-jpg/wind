-- WP12: courier/freight declared resource contracts and private objects.
-- PG-only operational tables; no legacy SQLite counterpart and no rows are
-- seeded. Declared scope is customer-declared contract data: it never
-- replaces an operator-measured order_requirements row (measured wins).
CREATE TABLE order_declared_scope (
  order_id BIGINT PRIMARY KEY REFERENCES orders(id),
  service TEXT NOT NULL CHECK(service IN ('parcel','freight')),
  item_count BIGINT CHECK(item_count BETWEEN 1 AND 200),
  length_mm BIGINT CHECK(length_mm BETWEEN 1 AND 100000),
  width_mm BIGINT CHECK(width_mm BETWEEN 1 AND 100000),
  height_mm BIGINT CHECK(height_mm BETWEEN 1 AND 100000),
  mass_grams BIGINT CHECK(mass_grams BETWEEN 1 AND 1000000000),
  volume_cm3 BIGINT CHECK(volume_cm3 BETWEEN 1 AND 1000000000),
  declared_value_minor BIGINT CHECK(declared_value_minor BETWEEN 0 AND 9007199254740991),
  equipment JSONB NOT NULL DEFAULT '[]'::jsonb,
  crew_count BIGINT CHECK(crew_count BETWEEN 1 AND 20),
  loading_after BIGINT CHECK(loading_after BETWEEN 0 AND 9007199254740991),
  loading_before BIGINT CHECK(loading_before BETWEEN 0 AND 9007199254740991),
  access_constraints JSONB NOT NULL DEFAULT '[]'::jsonb,
  pickup_promised_after BIGINT CHECK(pickup_promised_after BETWEEN 0 AND 9007199254740991),
  pickup_promised_before BIGINT CHECK(pickup_promised_before BETWEEN 0 AND 9007199254740991),
  dropoff_promised_before BIGINT CHECK(dropoff_promised_before BETWEEN 0 AND 9007199254740991),
  revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
  source_ref TEXT,
  payload_hash TEXT,
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  updated_at BIGINT NOT NULL CHECK(updated_at BETWEEN 0 AND 9007199254740991),
  CHECK((length_mm IS NULL) = (width_mm IS NULL) AND (width_mm IS NULL) = (height_mm IS NULL)),
  CHECK(loading_after IS NULL OR loading_before IS NULL OR loading_before >= loading_after),
  CHECK(pickup_promised_after IS NULL OR pickup_promised_before IS NULL OR pickup_promised_before >= pickup_promised_after),
  CHECK(pickup_promised_before IS NULL OR dropoff_promised_before IS NULL OR dropoff_promised_before >= pickup_promised_before),
  CHECK((service='parcel' AND item_count IS NOT NULL AND length_mm IS NOT NULL AND mass_grams IS NOT NULL
      AND volume_cm3 IS NOT NULL AND declared_value_minor IS NOT NULL)
    OR (service='freight' AND crew_count IS NOT NULL AND loading_after IS NOT NULL AND loading_before IS NOT NULL))
);
CREATE UNIQUE INDEX order_declared_scope_source_ref ON order_declared_scope(source_ref) WHERE source_ref IS NOT NULL;

-- Append-only custody facts. An uploaded private object is never a custody
-- record: custody changes only through these explicit actor rows.
CREATE TABLE custody_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  kind TEXT NOT NULL CHECK(kind IN ('collected','handed','returned')),
  actor_id BIGINT NOT NULL REFERENCES users(id),
  actor_role TEXT NOT NULL CHECK(actor_role IN ('customer','driver','admin')),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX custody_records_order ON custody_records(order_id, id);
CREATE TRIGGER custody_records_append_only BEFORE UPDATE OR DELETE ON custody_records FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Driver-reported actual load at pickup, compared with the effective scope.
CREATE TABLE order_scope_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  reporter_id BIGINT NOT NULL REFERENCES users(id),
  actual_item_count BIGINT NOT NULL CHECK(actual_item_count BETWEEN 1 AND 100000),
  actual_mass_grams BIGINT NOT NULL CHECK(actual_mass_grams BETWEEN 1 AND 1000000000),
  actual_length_mm BIGINT NOT NULL CHECK(actual_length_mm BETWEEN 1 AND 100000),
  actual_width_mm BIGINT NOT NULL CHECK(actual_width_mm BETWEEN 1 AND 100000),
  actual_height_mm BIGINT NOT NULL CHECK(actual_height_mm BETWEEN 1 AND 100000),
  outcome TEXT NOT NULL CHECK(outcome IN ('matched','mismatch')),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX order_scope_checks_order ON order_scope_checks(order_id, id);
CREATE TRIGGER order_scope_checks_append_only BEFORE UPDATE OR DELETE ON order_scope_checks FOR EACH ROW EXECUTE FUNCTION wp05_append_only();

-- Private objects (coded-but-off until Blob configuration exists). The
-- storage key is opaque and never enough on its own: reads need a clean
-- scan plus a short-lived, participant-bound read grant below.
CREATE TABLE private_objects (
  id UUID PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  uploader_id BIGINT NOT NULL REFERENCES users(id),
  purpose TEXT NOT NULL CHECK(purpose IN ('condition-photo','signature','document')),
  content_type TEXT NOT NULL,
  size_bytes BIGINT NOT NULL CHECK(size_bytes BETWEEN 1 AND 10485760),
  sha256 TEXT NOT NULL CHECK(sha256 ~ '^[a-f0-9]{64}$'),
  storage_key TEXT NOT NULL UNIQUE,
  scan_state TEXT NOT NULL CHECK(scan_state IN ('pending','clean','rejected')),
  retention_until BIGINT NOT NULL CHECK(retention_until BETWEEN 0 AND 9007199254740991),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991),
  updated_at BIGINT NOT NULL CHECK(updated_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX private_objects_order ON private_objects(order_id, created_at);

CREATE TABLE private_object_reads (
  token_hash TEXT PRIMARY KEY,
  object_id UUID NOT NULL REFERENCES private_objects(id),
  order_id BIGINT NOT NULL REFERENCES orders(id),
  subject_id BIGINT NOT NULL REFERENCES users(id),
  expires_at BIGINT NOT NULL CHECK(expires_at BETWEEN 0 AND 9007199254740991),
  created_at BIGINT NOT NULL CHECK(created_at BETWEEN 0 AND 9007199254740991)
);
CREATE INDEX private_object_reads_object ON private_object_reads(object_id);

