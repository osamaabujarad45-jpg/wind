-- WP06: no automatic canonical uniqueness migration, carrier approval or phone proof is seeded.
ALTER TABLE users ADD COLUMN phone_revision BIGINT NOT NULL DEFAULT 1 CHECK(phone_revision BETWEEN 1 AND 9007199254740991);
CREATE FUNCTION phone_identity_group(input TEXT) RETURNS TEXT LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE n TEXT;
BEGIN
 n:=regexp_replace(translate(input,'٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹','01234567890123456789'),'[[:space:]().-]','','g');
 IF n ~ '^05[69][0-9]{7}$' THEN RETURN '+970'||substr(n,2); END IF;
 IF n ~ '^5[69][0-9]{7}$' THEN RETURN '+970'||n; END IF;
 IF n ~ '^(\+|00)(970|972)5[69][0-9]{7}$' THEN RETURN '+970'||right(n,9); END IF;
 RETURN NULL;
END $$;
CREATE INDEX users_phone_group_review ON users(phone_identity_group(phone)) WHERE phone_identity_group(phone) IS NOT NULL;
CREATE TABLE phone_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id), display_phone TEXT NOT NULL, candidate_e164 TEXT NOT NULL,
 canonical_group TEXT NOT NULL, country_context TEXT NOT NULL CHECK(country_context='PS'), calling_code TEXT NOT NULL CHECK(calling_code IN('970','972')),
 verification_state TEXT NOT NULL CHECK(verification_state IN('unverified','verified','review_required')), verified_at BIGINT, updated_at BIGINT NOT NULL
);
CREATE TABLE phone_mappings (
 canonical_group TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), legacy_phone TEXT NOT NULL,
 routing_e164 TEXT NOT NULL, country_context TEXT NOT NULL CHECK(country_context='PS'),
 state TEXT NOT NULL CHECK(state IN('reviewed','verified','review_required','suspended','retired')),
 version BIGINT NOT NULL DEFAULT 1, reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_ref TEXT NOT NULL, reason TEXT NOT NULL, reviewed_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX phone_verified_mapping_per_user ON phone_mappings(user_id) WHERE state='verified';
CREATE TABLE phone_aliases (
 alias_e164 TEXT PRIMARY KEY, canonical_group TEXT NOT NULL REFERENCES phone_mappings(canonical_group)
);
CREATE TABLE phone_challenges (
 id UUID PRIMARY KEY, purpose TEXT NOT NULL CHECK(purpose IN('verify','change','recovery')),
 user_id BIGINT REFERENCES users(id), actor_id BIGINT REFERENCES users(id), actor_role TEXT,
 identity_revision BIGINT, mapping_version BIGINT, canonical_group TEXT NOT NULL, target_e164 TEXT NOT NULL,
 display_phone TEXT NOT NULL, country_context TEXT NOT NULL CHECK(country_context='PS'),
 device_hash TEXT NOT NULL, session_hash TEXT, scope_hash TEXT NOT NULL,
 code_digest TEXT NOT NULL, secret_version TEXT NOT NULL, created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
 attempts BIGINT NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5), resend_at BIGINT NOT NULL,
 consumed_at BIGINT, superseded_at BIGINT,
 delivery_state TEXT NOT NULL CHECK(delivery_state IN('prepared','requested','accepted','failed','unknown','obsolete','suppressed')),
 provider_transaction_id UUID NOT NULL, provider_reference TEXT, provider_status BIGINT,
 send_started_at BIGINT, send_lease_until BIGINT, completed_at BIGINT, budget_day BIGINT,
 budget_cost_minor BIGINT NOT NULL DEFAULT 0, budget_released BIGINT NOT NULL DEFAULT 0 CHECK(budget_released IN(0,1))
);
CREATE INDEX phone_challenge_scope ON phone_challenges(scope_hash,created_at);
CREATE INDEX phone_challenge_number ON phone_challenges(canonical_group,created_at);
CREATE INDEX phone_challenge_device ON phone_challenges(device_hash,created_at);
CREATE INDEX phone_challenge_stale ON phone_challenges(delivery_state,send_lease_until);
CREATE TABLE phone_command_results (
 scope_hash TEXT NOT NULL, command_id UUID NOT NULL, payload_hash TEXT NOT NULL,
 http_status BIGINT NOT NULL, response JSONB NOT NULL, created_at BIGINT NOT NULL,
 PRIMARY KEY(scope_hash,command_id)
);
CREATE TABLE phone_rate_windows (
 bucket_hash TEXT NOT NULL, period_ms BIGINT NOT NULL, window_start BIGINT NOT NULL, count BIGINT NOT NULL,
 PRIMARY KEY(bucket_hash,period_ms,window_start)
);
CREATE TABLE phone_provider_budget (
 day BIGINT PRIMARY KEY, reserved_messages BIGINT NOT NULL CHECK(reserved_messages>=0),
 reserved_minor BIGINT NOT NULL CHECK(reserved_minor>=0)
);
CREATE TABLE phone_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id), actor_id BIGINT REFERENCES users(id),
 challenge_id UUID REFERENCES phone_challenges(id), action TEXT NOT NULL, reason TEXT NOT NULL, evidence_ref TEXT,
 created_at BIGINT NOT NULL
);
CREATE TRIGGER phone_audit_immutable BEFORE UPDATE OR DELETE ON phone_audit FOR EACH ROW EXECUTE FUNCTION wp05_append_only();
CREATE FUNCTION phone_security_revision() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF (NEW.phone,NEW.password,NEW.role,NEW.status) IS DISTINCT FROM (OLD.phone,OLD.password,OLD.role,OLD.status) THEN
  NEW.phone_revision:=OLD.phone_revision+1;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER users_phone_security_revision BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION phone_security_revision();
CREATE FUNCTION phone_legacy_change() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF NEW.phone IS DISTINCT FROM OLD.phone THEN
  UPDATE phone_profiles SET verification_state='review_required',verified_at=NULL WHERE user_id=NEW.id;
  UPDATE phone_mappings SET state='review_required',version=version+1 WHERE user_id=NEW.id AND state IN('reviewed','verified');
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER users_phone_mapping_revision AFTER UPDATE OF phone ON users FOR EACH ROW EXECUTE FUNCTION phone_legacy_change();
