// Deliberately minimal WP02 adapter schema: proves the existing HTTP handler graph actually uses pg.
// This is NOT the WP03 application schema or an import/parity migration.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Persistence } from '../server/db/persistence.ts';
import { apiCaller } from './support/api.mjs';
const connectionString = process.env.WIND_TEST_DATABASE_URL ?? 'postgresql://fastship_test@127.0.0.1:55473/fastship_test';
const schema = `wp02_api_${randomUUID().replaceAll('-', '')}`;
const seed = new Persistence({ connectionString });
await seed.run(`CREATE SCHEMA ${schema}`);
await seed.close();
const setup = new Persistence({ connectionString, pool: { options: `-c search_path=${schema},public` } });
await setup.migrate(5702002, async () => {
  await setup.run(`CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phone TEXT NOT NULL UNIQUE, name TEXT NOT NULL, password TEXT NOT NULL,
    role TEXT NOT NULL, status TEXT NOT NULL, vehicle TEXT, plate TEXT, created_at BIGINT NOT NULL,
    phone_verified_at BIGINT, email TEXT, email_verified_at BIGINT, approved_at BIGINT, consent_at BIGINT, consent_version TEXT,
    heading_city TEXT, heading_until BIGINT)`);
  await setup.run('CREATE TABLE sessions (token_hash TEXT PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),created_at BIGINT NOT NULL,last_seen_at BIGINT)');
  await setup.run('CREATE TABLE firebase_resets (user_id BIGINT PRIMARY KEY REFERENCES users(id),requested_at BIGINT NOT NULL)');
  await setup.run('CREATE TABLE settings (key TEXT PRIMARY KEY,value DOUBLE PRECISION NOT NULL)');
  await setup.run('CREATE TABLE request_limits (key TEXT PRIMARY KEY,count INTEGER NOT NULL,until BIGINT NOT NULL)');
  await setup.run(`CREATE TABLE subscriptions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT REFERENCES users(id),plan TEXT,status TEXT,
    price DOUBLE PRECISION,activated_at BIGINT,ends_at BIGINT,created_at BIGINT)`);
  await setup.run('CREATE TABLE push_subscriptions (endpoint TEXT PRIMARY KEY,user_id BIGINT REFERENCES users(id))');
});
Object.assign(process.env, { NODE_ENV: 'test', WIND_DATABASE_URL: connectionString, WIND_POSTGRES_TEST_ONLY: '1', WIND_POSTGRES_TEST_SCHEMA: schema });
for (const key of ['WIND_EMAIL_FROM', 'CLOUDFLARE_ACCOUNT_ID', 'CLOUDFLARE_EMAIL_TOKEN', 'WIND_IDENTITY_MODE', 'WIND_CONTACT_VERIFICATION_REQUIRED', 'WIND_FIREBASE_API_KEY', 'WIND_FIREBASE_SERVICE_ACCOUNT']) delete process.env[key];
const { server, shutdown, persistence, db } = await import('../server/main.ts');
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const call = apiCaller(() => `http://127.0.0.1:${server.address().port}/api`);
try {
  assert.equal(persistence.backend, 'postgres');
  assert.deepEqual(await call('/health'), { ok: true });
  // Readiness requires the Entra and idle-session migrations as well as WP16.
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('CREATE TABLE schema_migrations (version BIGINT PRIMARY KEY, applied_at BIGINT NOT NULL)');
  await setup.run('INSERT INTO schema_migrations SELECT generate_series(3,17), 0');
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('INSERT INTO schema_migrations VALUES(18, 0)');
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('INSERT INTO schema_migrations VALUES(19, 0)');
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('INSERT INTO schema_migrations VALUES(20, 0)');
  await setup.run('INSERT INTO schema_migrations VALUES(21, 0)');
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('INSERT INTO schema_migrations VALUES(30, 0)');
  assert.deepEqual(await call('/ready'), { ok: true, schema: 30 });
  await setup.run('DELETE FROM schema_migrations WHERE version=19');
  assert.deepEqual(await call('/ready', { expect: 503 }), { error: 'unavailable' });
  await setup.run('INSERT INTO schema_migrations VALUES(19, 0)');
  const registered = await call('/auth/register', { body: { name: 'WP02 synthetic customer', phone: '0599610001', password: 'synthetic-pass-only' } });
  assert.equal(typeof registered.user.id, 'number');
  assert.equal(registered.user.role, 'customer');
  assert.equal(db.prepare('SELECT COUNT(*) n FROM users').get().n, 0, 'SQLite did not receive the registration');
  assert.equal((await setup.one('SELECT COUNT(*) n FROM users')).n, 1);
  const session = await call('/auth/login', { body: { phone: '0599610001', password: 'synthetic-pass-only' } });
  assert.equal(session.user.id, registered.user.id);
  const me = await call('/me', { token: session.token });
  assert.equal(me.user.name, 'WP02 synthetic customer');
  // Bad credentials persist attempt counters through the PG UPSERT path.
  await call('/auth/login', { body: { phone: '0599610001', password: 'wrong' }, expect: 401 });
  assert.ok((await setup.one('SELECT COUNT(*) n FROM request_limits')).n > 0);
  await call('/auth/logout', { token: session.token, body: {} });
  await call('/me', { token: registered.token, expect: 401 });
  assert.equal((await setup.one('SELECT COUNT(*) n FROM sessions')).n, 0);
  console.log(`WP02 real PG HTTP slice passed: health, readiness, register, login, me, failed-login throttles, logout; schema ${schema}`);
} finally { await shutdown(); await setup.close(); }
