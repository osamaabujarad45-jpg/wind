import assert from 'node:assert/strict';
import { etaProjection, fareAmounts, acceptedFareChange, validFareChange, offerFailure } from '../server/domain/journey.ts';
import { readEta, readJourney } from '../src/wire-contracts.ts';
import { deadlineSeconds, noteResponseClock } from '../src/api-clock.ts';
const eta = etaProjection(120, 1000, 31000, 1001);
assert.deepEqual([eta.minSeconds,eta.maxSeconds,eta.accuracy], [120,300,'unknown']);
assert.equal(etaProjection(120,1000,31000,31000), undefined, 'exact validity boundary expires');
for (const raw of [-1,NaN,Infinity,Number.MAX_SAFE_INTEGER+1]) assert.equal(etaProjection(raw,1000,31000,1001),undefined);
assert.equal(etaProjection(null,1000,31000,1001,'quote_band',[60,120]).rawSeconds,null);
assert.equal(etaProjection(10,1000,31000,1001,'heuristic',[20,30]),undefined);
assert.equal(readEta(eta),eta);
assert.throws(()=>readEta({...eta,validity:{...eta.validity,expiresAt:1}}));
noteResponseClock(eta,100,500);
assert.equal(deadlineSeconds(31000,eta,0,500),30);
assert.equal(deadlineSeconds(31000,eta,9999999999,30500),0);
assert.equal(deadlineSeconds(31000,eta,-9999999999,30500),0,'wall clock cannot extend an anchored deadline');
const jobClock = { serverTime: 1001 };
noteResponseClock({ jobs: [{ journey: jobClock }] },100,500);
assert.equal(deadlineSeconds(31000,jobClock,-9999999999,30500),0,'paginated cards retain monotonic validity too');
assert.deepEqual(fareAmounts(20,5),{grossMinor:2000,discountMinor:500,dueMinor:1500});
for(const args of [[1,2],[-1,0],[Infinity,0],[Number.MAX_SAFE_INTEGER,0]]) assert.throws(()=>fareAmounts(...args));
const change=acceptedFareChange('11111111-1111-4111-8111-111111111111',1000,fareAmounts(20,5),fareAmounts(20,10));
assert.equal(validFareChange(change),true,'discount-only change is a fare event');
assert.equal(acceptedFareChange(change.changeId,1000,change.before,change.before),undefined);
assert.equal(readJourney({schemaVersion:1,serverTime:1001,lastFareChange:change}).lastFareChange,change);
assert.throws(()=>readJourney({schemaVersion:1,serverTime:1001,boarding:{policy:'all_trips',reason:'provider_setting',required:true,locked:true,shouldShow:true,isVerified:false,pinIssuedAt:1000,pinRevision:1,pin:'1234'}}));
assert.equal(offerFailure('decline','not_found',404).recovery,'stop');
assert.equal(offerFailure('accept','offer_expired',409).recovery,'refresh');
assert.equal(offerFailure('accept','unauthorized',401).recovery,'sign_in');
assert.equal(offerFailure('accept','server_error',503).recovery,'reconcile');
console.log('Journey ETA validity, monotonic deadlines, safe money and per-verb failure projections passed');
